import assert from "node:assert/strict";
import { createGame, runDraft, simulateSeason, applyDecision, migrateGame } from "../../js/engine/game-engine.js";
import { migrateCoachingSystems, getCoachingDashboard, createCoachingMeeting, applyCoachingMeetingChoice, prepareCoachingSeason } from "../../js/engine/coaching-systems-engine.js";

let game=createGame({name:"Coach Test",position:"PG",archetype:"Floor General",seed:"coaching-2016"});
game=runDraft(game);
const state=migrateCoachingSystems(game);
assert.equal(state.version,1);
const dash=getCoachingDashboard(game);
assert.ok(dash.coach?.systemId);
assert.ok(["short","development","flexible"].includes(dash.coach.rotationPolicy));
assert.ok(dash.fit>=20&&dash.fit<=98);
const meeting=createCoachingMeeting(game);
assert.equal(meeting.type,"coachingMeeting");
assert.equal(meeting.options.length,4);
applyCoachingMeetingChoice(game,meeting.options.find(x=>x.id==="coach_defense"));
const plan=prepareCoachingSeason(game,{player:game.player,coach:dash.coach});
assert.equal(plan.focus,"defense");
assert.ok(Number.isFinite(plan.minutesModifier));
assert.ok(Number.isFinite(plan.developmentModifier));
game=simulateSeason(game);
if(game.pendingDecision?.type==="tradeDeadline")game=applyDecision(game,game.pendingDecision.options[0].id),game=simulateSeason(game);
const season=game.player.career.at(-1);
assert.ok(season.coachingSystem);
assert.ok(Number.isFinite(season.coachingFit));
assert.ok(season.rotationPolicy);
const old={version:16,season:2030,phase:"season",player:structuredClone(game.player),league:structuredClone(game.league),atlas:{schema:10},settings:{difficulty:"normal"}};
const migrated=migrateGame(old);
assert.ok(migrated.atlas.schema>=11);
assert.ok(migrated.atlas.migrations.some(x=>x.id==="coaching-systems"));
assert.equal(migrated.careerMode.coachingSystems.version,1);
console.log("✓ NBA Glory 2.0.16 Coaching Systems");
