import assert from 'node:assert/strict';
import { migrateNcaaDraft, processNcaaDraftSeason, getDraftWorld, resolveUserDraft } from '../js/engine/ncaa-draft-engine.js';
const game={season:2028,world:{}};
migrateNcaaDraft(game);
let dash=getDraftWorld(game);
assert.equal(dash.universities.length,12);
assert.equal(dash.currentClass.prospects.length,30);
assert.equal(dash.currentClass.mock.length,30);
const cls=processNcaaDraftSeason(game);
assert.ok(cls.marchMadness.champion);
assert.ok(cls.marchMadness.finalFour.length===4);
assert.ok(cls.awards.playerOfYear);
assert.ok(cls.prospects.some(p=>p.stats?.games));
const result=resolveUserDraft(game,{score:84,projected:8,position:'SG'});
assert.ok(result.pick>=1&&result.pick<=60);
assert.equal(result.mock.length,10);
game.season=2029;migrateNcaaDraft(game);
assert.equal(getDraftWorld(game).currentClass.season,2029);
console.log('✓ NCAA & Draft Revolution: universidades, prospectos, March Madness, mock y Draft Night');
